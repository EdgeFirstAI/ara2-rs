//! # YOLOv8 Inference on ARA-2 NPU
//!
//! End-to-end detection and instance segmentation on the ARA-2 NPU, using the
//! EdgeFirst HAL for GPU preprocessing, decoding, and overlay rendering.
//!
//! ## Pipeline
//!
//! ```text
//! JPEG → [GPU] letterbox resize → PlanarRGB → [NPU] inference
//!                                                      │
//!                                              ┌───────┴────────┐
//!                                         boxes/scores      proto data
//!                                              │                │
//!                                    [1] decode_proto           │
//!                                      NMS + dequant            │
//!                                              │                │
//!                                    [2] materialize_masks ─────┘
//!                                      CPU dot-product
//!                                      coeff × protos → bitmaps
//!                                              │
//!                                    [3] draw_decoded_masks
//!                                      GL overlay onto canvas
//! ```
//!
//! ## Usage
//!
//! See `yolov8 --help` for the full flag reference (generated by clap).
//!
//! ## Features
//!
//! - Automatic detection vs segmentation from DVM metadata or output shapes
//! - Letterbox resize preserving aspect ratio (YOLO gray padding)
//! - DMA-backed intermediate tensors for zero-copy GPU → NPU data transfer
//! - HAL Decoder with automatic dequantization and NMS
//! - Per-stage timing: preprocess / inference / decode / materialize / draw
//! - COCO class labels as fallback when DVM metadata has no labels

