/// Static-image YOLOv8 detection / instance segmentation on the ARA-2 NPU.
#[derive(Parser)]
struct Args {
    /// Path to the compiled DVM model file (e.g. `yolov8n-seg.dvm`).
    model: PathBuf,

    /// Path to the input JPEG/PNG image.
    image: PathBuf,

    /// Save the annotated overlay next to the input as `<image>_overlay.jpg`.
    #[arg(long)]
    save: bool,

    /// Minimum confidence score for detections.
    // Lower default (0.25) than the live example (0.50): static-image
    // inspection benefits from surfacing lower-confidence detections
    // alongside high-confidence ones for visual review.
    #[arg(long, default_value_t = 0.25)]
    threshold: f32,

    /// IoU threshold for non-maximum suppression.
    #[arg(long, default_value_t = 0.45)]
    iou: f32,

    /// Run N benchmark iterations after the single inference and print timing statistics.
    #[arg(long, default_value_t = 0)]
    benchmark: usize,

    /// Segmentation mask color assignment.
    #[arg(long, value_enum, default_value_t = ColorModeArg::Class)]
    color_mode: ColorModeArg,

    /// UNIX socket path for the ARA-2 proxy service.
    #[arg(long, default_value_t = ara2::DEFAULT_SOCKET.to_string())]
    socket: String,
}

/// How segmentation mask colors are assigned.
///
/// This is a command-line mirror of [`ColorMode`] from `edgefirst-hal`.
#[derive(Clone, Copy, Debug, ValueEnum)]
enum ColorModeArg {
    /// One color per class label. Same label → same color across frames.
    Class,
    /// One color per detected instance, cycling per frame.
    Instance,
    /// One color per track ID (requires a tracking-enabled pipeline).
    Track,
}

impl From<ColorModeArg> for ColorMode {
    fn from(v: ColorModeArg) -> Self {
        match v {
            ColorModeArg::Class => ColorMode::Class,
            ColorModeArg::Instance => ColorMode::Instance,
            ColorModeArg::Track => ColorMode::Track,
        }
    }
}

