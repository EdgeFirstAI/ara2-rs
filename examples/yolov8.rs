//! # YOLOv8 Inference on ARA-2 NPU
//!
//! End-to-end detection and instance segmentation on the ARA-2 NPU, using the
//! EdgeFirst HAL for GPU preprocessing, decoding, and overlay rendering.
//!
//! ## Pipeline
//!
//! ```text
//! JPEG → [GPU] letterbox resize → PlanarRGB → [NPU] inference
//!                                                      │
//!                                              ┌───────┴────────┐
//!                                         boxes/scores      proto data
//!                                              │                │
//!                                    [1] decode_proto           │
//!                                      NMS + dequant            │
//!                                              │                │
//!                                    [2] materialize_masks ─────┘
//!                                      CPU dot-product
//!                                      coeff × protos → bitmaps
//!                                              │
//!                                    [3] draw_decoded_masks
//!                                      GL overlay onto canvas
//! ```
//!
//! ## Models
//!
//! Official pre-trained models are published in the EdgeFirst model zoo on
//! Hugging Face:
//!
//! - Detection: <https://huggingface.co/EdgeFirst/yolov8-det>
//! - Segmentation: <https://huggingface.co/EdgeFirst/yolov8-seg>
//!
//! Each repository ships one directory per target; the ARA-2 builds are the
//! int16 `.dvm` exports under `ara240/`, in `n`/`s`/`m` sizes.
//!
//! ```sh
//! curl -LO https://huggingface.co/EdgeFirst/yolov8-det/resolve/main/ara240/yolov8n-det-int16.dvm
//! curl -LO https://huggingface.co/EdgeFirst/yolov8-seg/resolve/main/ara240/yolov8n-seg-int16.dvm
//! ```
//!
//! Every export embeds an `edgefirst.json` schema and the class `labels.txt`
//! in a ZIP trailer appended to the `.dvm`. That schema is where the
//! per-output `normalized` flag and named `dshape` come from — the NPU
//! runtime reports neither, and a model emitting pixel-space boxes is
//! misread without them. An export with no trailer still runs, falling back
//! to the built-in COCO labels and a canonical Ultralytics axis naming.
//!
//! This example pins `DecoderVersion::Yolov8`, so it decodes the
//! `yolov8-det` and `yolov8-seg` repositories.
//!
//! ## Usage
//!
//! See `yolov8 --help` for the full flag reference (generated by clap).
//!
//! ## Features
//!
//! - Automatic detection vs segmentation from DVM metadata or output shapes
//! - Letterbox resize preserving aspect ratio (YOLO gray padding)
//! - DMA-backed intermediate tensors for zero-copy GPU → NPU data transfer
//! - HAL Decoder with automatic dequantization and NMS
//! - Per-stage timing: preprocess / inference / decode / materialize / draw
//! - COCO class labels as fallback when DVM metadata has no labels

