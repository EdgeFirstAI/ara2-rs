/// Live YOLOv8 detection / instance segmentation on the ARA-2 NPU.
///
/// Captures camera frames via libcamera, runs inference on the NPU, and
/// displays results directly on a Wayland compositor via DMA-BUF.
#[derive(Parser)]
struct Args {
    /// Path to the compiled DVM model file (e.g. `yolov8n-seg.dvm`).
    model: PathBuf,

    /// Minimum confidence score for detections.
    // Higher default (0.50) than the static example (0.25): live video
    // wants fewer false positives per frame to keep the overlay stable.
    #[arg(long, default_value_t = 0.50)]
    threshold: f32,

    /// IoU threshold for non-maximum suppression.
    #[arg(long, default_value_t = 0.45)]
    iou: f32,

    /// Non-maximum suppression policy.
    #[arg(long, value_enum, default_value_t = NmsArg::Auto)]
    nms: NmsArg,

    /// Camera capture width in pixels.
    #[arg(long, default_value_t = 1920)]
    width: usize,

    /// Camera capture height in pixels.
    #[arg(long, default_value_t = 1080)]
    height: usize,

    /// libcamera camera ID. When omitted, the first available camera is used.
    #[arg(long)]
    camera_name: Option<String>,

    /// UNIX socket path for the ARA-2 proxy service. When omitted, the proxy
    /// is located as `Session::connect` does.
    #[arg(long)]
    socket: Option<String>,

    /// Camera pixel format.
    #[arg(long, value_enum, default_value_t = FormatArg::Nv12)]
    format: FormatArg,

    /// Segmentation mask color assignment.
    #[arg(long, value_enum, default_value_t = ColorModeArg::Class)]
    color_mode: ColorModeArg,

    /// Open a fullscreen window at the output's resolution.
    #[arg(long)]
    fullscreen: bool,

    /// Box colour of each class, in label order, as comma-separated hex
    /// `RRGGBB` values.
    #[arg(long, value_parser = parse_class_colors)]
    class_colors: Option<ClassColors>,

    /// Box outline width in display pixels (HAL default 3).
    #[arg(long)]
    line_width: Option<NonZeroU32>,

    /// Input buffers the letterbox and inference stages alternate between.
    #[arg(long, default_value = "2")]
    slots: NonZeroUsize,

    /// Fixed exposure time in microseconds; turns automatic exposure off.
    #[arg(long, requires = "gain")]
    exposure: Option<i32>,

    /// Fixed analogue gain; turns automatic exposure off.
    #[arg(long, requires = "exposure")]
    gain: Option<f32>,

    /// Leave exposure and gain to the camera; cancels an earlier
    /// `--exposure` and `--gain`.
    #[arg(long, overrides_with_all = ["exposure", "gain"])]
    auto_exposure: bool,
}

/// Camera capture pixel format selectable from the command line.
///
/// This is a command-line mirror of [`PixelFormat`] from `edgefirst-tensor`.
#[derive(Clone, Copy, Debug, ValueEnum)]
enum FormatArg {
    /// Semi-planar YUV 4:2:0 — the embedded-Linux default.
    Nv12,
    /// Packed YUV 4:2:2 — common on USB UVC cameras. Alias: `yuy2`.
    #[value(alias = "yuy2")]
    Yuyv,
}

impl From<FormatArg> for PixelFormat {
    fn from(v: FormatArg) -> Self {
        match v {
            FormatArg::Nv12 => PixelFormat::Nv12,
            FormatArg::Yuyv => PixelFormat::Yuyv,
        }
    }
}

/// How segmentation mask colors are assigned.
///
/// This is a command-line mirror of [`ColorMode`] from `edgefirst-image`.
#[derive(Clone, Copy, Debug, ValueEnum)]
enum ColorModeArg {
    /// One color per class label. Same label → same color across frames.
    Class,
    /// One color per detected instance, cycling per frame.
    Instance,
    /// One color per track ID (requires a tracking-enabled pipeline).
    Track,
}

impl From<ColorModeArg> for ColorMode {
    fn from(v: ColorModeArg) -> Self {
        match v {
            ColorModeArg::Class => ColorMode::Class,
            ColorModeArg::Instance => ColorMode::Instance,
            ColorModeArg::Track => ColorMode::Track,
        }
    }
}

/// Non-maximum suppression policy.
///
/// This is a command-line mirror of [`Nms`] from `edgefirst-decoder`.
#[derive(Clone, Copy, Debug, ValueEnum)]
enum NmsArg {
    /// The policy in the model's `edgefirst.json`, else class-aware.
    Auto,
    /// Suppress overlapping boxes whatever their class.
    Agnostic,
    /// Suppress only overlapping boxes of the same class.
    Aware,
}

impl From<NmsArg> for Nms {
    fn from(v: NmsArg) -> Self {
        match v {
            NmsArg::Auto => Nms::Auto,
            NmsArg::Agnostic => Nms::ClassAgnostic,
            NmsArg::Aware => Nms::ClassAware,
        }
    }
}

/// Palette entries the HAL accepts in `set_class_colors`.
const MAX_CLASS_COLORS: usize = 20;

/// `--class-colors`: opaque RGBA colours in label order.
#[derive(Clone, Debug)]
struct ClassColors(Vec<[u8; 4]>);

/// Parses `--class-colors`: comma-separated `RRGGBB` colours, with or
/// without a leading `#`, at most [`MAX_CLASS_COLORS`] of them.
fn parse_class_colors(value: &str) -> std::result::Result<ClassColors, String> {
    let parse = |text: &str| {
        let hex = text.trim().trim_start_matches('#');
        let rgb = u32::from_str_radix(hex, 16)
            .ok()
            .filter(|_| hex.len() == 6)?;
        let [_, red, green, blue] = rgb.to_be_bytes();
        Some([red, green, blue, 255])
    };
    value
        .split(',')
        .map(parse)
        .collect::<Option<Vec<_>>>()
        .filter(|colors| colors.len() <= MAX_CLASS_COLORS)
        .map(ClassColors)
        .ok_or_else(|| format!("expected up to {MAX_CLASS_COLORS} comma-separated RRGGBB values"))
}

// ── Wayland display (direct DMA-BUF submission, no EGL/GL) ──────────────────

/// DRM fourcc `ABGR8888`: R, G, B, A bytes in memory order, which is the
/// layout of the HAL's [`PixelFormat::Rgba`].
const DRM_FORMAT_ABGR8888: u32 = u32::from_le_bytes(*b"AB24");

/// Event-loop state for the Wayland connection.
#[derive(Debug, Default)]
struct DisplayState {
    compositor: Option<wl_compositor::WlCompositor>,
    viewporter: Option<wp_viewporter::WpViewporter>,
    wm_base: Option<xdg_wm_base::XdgWmBase>,
    dmabuf: Option<zwp_linux_dmabuf_v1::ZwpLinuxDmabufV1>,
    surface: Option<wl_surface::WlSurface>,
    configured: bool,
    /// Size the compositor asked for in the last `xdg_toplevel.configure`;
    /// zero when it left the choice to the client.
    configured_size: (i32, i32),
    closed: bool,
    /// One `wl_buffer` per DMA-BUF fd, imported on first submit.
    buffers: HashMap<i32, wl_buffer::WlBuffer>,
    /// The fds of buffers the compositor holds: set on submit and cleared by
    /// `wl_buffer.release`. Drawing into one of these tears the picture.
    busy: HashSet<i32>,
}

/// Buffers of another size than the window, which the compositor scales.
struct Scaled {
    size: (i32, i32),
    _viewport: wp_viewport::WpViewport,
}

/// An XDG toplevel window that presents DMA-BUF RGBA buffers.
struct WaylandDisplay {
    conn: Connection,
    queue: EventQueue<DisplayState>,
    state: DisplayState,
    width: i32,
    height: i32,
    scaled: Option<Scaled>,
}

impl WaylandDisplay {
    /// Connect via `$WAYLAND_DISPLAY`, bind the globals and wait for the
    /// window's first configure.
    ///
    /// With `fullscreen`, the window takes the size the compositor configures
    /// (the output's resolution) rather than `width` x `height`.
    fn new(width: usize, height: usize, title: &str, fullscreen: bool) -> Result<Self> {
        let width = i32::try_from(width).map_err(|_| Error::display("width out of range"))?;
        let height = i32::try_from(height).map_err(|_| Error::display("height out of range"))?;
        let conn = Connection::connect_to_env()
            .map_err(|e| Error::display(format!("no Wayland compositor: {e}")))?;
        let mut queue = conn.new_event_queue();
        let qh = queue.handle();
        conn.display().get_registry(&qh, ());

        let mut state = DisplayState::default();
        queue
            .roundtrip(&mut state)
            .map_err(|e| Error::display(format!("registry roundtrip: {e}")))?;

        let compositor = state
            .compositor
            .as_ref()
            .ok_or_else(|| Error::display("compositor lacks wl_compositor"))?;
        let wm_base = state
            .wm_base
            .as_ref()
            .ok_or_else(|| Error::display("compositor lacks xdg_wm_base"))?;
        if state.dmabuf.is_none() {
            return Err(Error::display("compositor lacks zwp_linux_dmabuf_v1"));
        }

        let surface = compositor.create_surface(&qh, ());
        let xdg_surface = wm_base.get_xdg_surface(&surface, &qh, ());
        let toplevel = xdg_surface.get_toplevel(&qh, ());
        toplevel.set_title(title.to_string());
        toplevel.set_app_id("ara2-yolov8-live".to_string());
        if fullscreen {
            toplevel.set_fullscreen(None);
        }
        surface.commit();
        state.surface = Some(surface);

        while !state.configured {
            queue
                .blocking_dispatch(&mut state)
                .map_err(|e| Error::display(format!("dispatch: {e}")))?;
        }

        let (width, height) = match state.configured_size {
            (w, h) if fullscreen && w > 0 && h > 0 => (w, h),
            _ => (width, height),
        };
        Ok(Self {
            conn,
            queue,
            state,
            width,
            height,
            scaled: None,
        })
    }

    /// Present `width` x `height` buffers scaled to the window, returning
    /// `false` when the compositor cannot scale them.
    fn scale_buffers(&mut self, width: usize, height: usize) -> Result<bool> {
        let Some(viewporter) = self.state.viewporter.as_ref() else {
            return Ok(false);
        };
        let width = i32::try_from(width).map_err(|_| Error::display("width out of range"))?;
        let height = i32::try_from(height).map_err(|_| Error::display("height out of range"))?;
        let surface = self.state.surface.as_ref().expect("created in new()");
        let viewport = viewporter.get_viewport(surface, &self.queue.handle(), ());
        viewport.set_destination(self.width, self.height);
        self.scaled = Some(Scaled {
            size: (width, height),
            _viewport: viewport,
        });
        Ok(true)
    }

    /// The window size in pixels.
    fn size(&self) -> (usize, usize) {
        (
            self.width.unsigned_abs() as usize,
            self.height.unsigned_abs() as usize,
        )
    }

    /// The index of a buffer in `fds` that is free to draw into, or `None`
    /// when the frame cannot be drawn.
    ///
    /// A buffer is free once `wl_buffer.release` says the compositor no
    /// longer reads it. A closed window has no free buffer;
    /// [`Self::is_open`] reports it.
    fn free_buffer(&mut self, fds: &[OwnedFd]) -> Result<Option<usize>> {
        self.dispatch_pending()?;
        if self.state.closed {
            return Ok(None);
        }
        Ok(fds
            .iter()
            .position(|fd| !self.state.busy.contains(&fd.as_raw_fd())))
    }

    /// Present the RGBA DMA-BUF `fd`, whose rows are `stride` bytes apart and
    /// which [`Self::free_buffer`] returned.
    ///
    /// Every frame is committed as soon as it is drawn. The compositor shows
    /// the newest one at each refresh and releases those it replaced, so the
    /// display never waits on the pipeline or the pipeline on the display.
    fn present(&mut self, fd: BorrowedFd<'_>, stride: u32) -> Result<()> {
        let qh = self.queue.handle();
        let (w, h) = self
            .scaled
            .as_ref()
            .map_or((self.width, self.height), |scaled| scaled.size);
        let raw = fd.as_raw_fd();
        let dmabuf = self.state.dmabuf.as_ref().expect("bound in new()");
        let buffer = self.state.buffers.entry(raw).or_insert_with(|| {
            let params = dmabuf.create_params(&qh, ());
            params.add(fd, 0, 0, stride, 0, 0);
            let buffer = params.create_immed(
                w,
                h,
                DRM_FORMAT_ABGR8888,
                zwp_linux_buffer_params_v1::Flags::empty(),
                &qh,
                raw,
            );
            params.destroy();
            buffer
        });

        let surface = self.state.surface.as_ref().expect("created in new()");
        surface.attach(Some(buffer), 0, 0);
        surface.damage_buffer(0, 0, w, h);
        self.state.busy.insert(raw);
        surface.commit();
        self.conn
            .flush()
            .map_err(|e| Error::display(format!("flush: {e}")))
    }

    /// Process pending events and report whether the window is still open.
    fn is_open(&mut self) -> Result<bool> {
        self.dispatch_pending()?;
        Ok(!self.state.closed)
    }

    fn dispatch_pending(&mut self) -> Result<()> {
        // `dispatch_pending` only drains what is already queued; reading the
        // socket first is what lets buffer releases and close events arrive
        // without blocking.
        if let Some(guard) = self.queue.prepare_read() {
            match guard.read() {
                Ok(_) => {}
                Err(wayland_client::backend::WaylandError::Io(e))
                    if e.kind() == std::io::ErrorKind::WouldBlock => {}
                Err(e) => return Err(Error::display(format!("read: {e}"))),
            }
        }
        self.queue
            .dispatch_pending(&mut self.state)
            .map_err(|e| Error::display(format!("dispatch: {e}")))?;
        self.conn
            .flush()
            .map_err(|e| Error::display(format!("flush: {e}")))?;
        Ok(())
    }
}

impl Dispatch<wl_registry::WlRegistry, ()> for DisplayState {
    fn event(
        state: &mut Self,
        registry: &wl_registry::WlRegistry,
        event: wl_registry::Event,
        (): &(),
        _: &Connection,
        qh: &QueueHandle<Self>,
    ) {
        if let wl_registry::Event::Global {
            name,
            interface,
            version,
        } = event
        {
            match interface.as_str() {
                "wl_compositor" => {
                    state.compositor = Some(registry.bind(name, version.min(4), qh, ()));
                }
                "wp_viewporter" => {
                    state.viewporter = Some(registry.bind(name, 1, qh, ()));
                }
                "xdg_wm_base" => {
                    state.wm_base = Some(registry.bind(name, version.min(1), qh, ()));
                }
                "zwp_linux_dmabuf_v1" => {
                    state.dmabuf = Some(registry.bind(name, version.min(3), qh, ()));
                }
                _ => {}
            }
        }
    }
}

impl Dispatch<xdg_wm_base::XdgWmBase, ()> for DisplayState {
    fn event(
        _: &mut Self,
        wm_base: &xdg_wm_base::XdgWmBase,
        event: xdg_wm_base::Event,
        (): &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        if let xdg_wm_base::Event::Ping { serial } = event {
            wm_base.pong(serial);
        }
    }
}

impl Dispatch<xdg_surface::XdgSurface, ()> for DisplayState {
    fn event(
        state: &mut Self,
        xdg_surface: &xdg_surface::XdgSurface,
        event: xdg_surface::Event,
        (): &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        if let xdg_surface::Event::Configure { serial } = event {
            xdg_surface.ack_configure(serial);
            state.configured = true;
        }
    }
}

impl Dispatch<xdg_toplevel::XdgToplevel, ()> for DisplayState {
    fn event(
        state: &mut Self,
        _: &xdg_toplevel::XdgToplevel,
        event: xdg_toplevel::Event,
        (): &(),
        _: &Connection,
        _: &QueueHandle<Self>,
    ) {
        match event {
            xdg_toplevel::Event::Close => state.closed = true,
            xdg_toplevel::Event::Configure { width, height, .. } => {
                state.configured_size = (width, height);
            }
            _ => {}
        }
    }
}

