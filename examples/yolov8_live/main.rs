/// The runtime index, shape and element type of each output the decoder
/// reads, in the order it takes them (see [`output_layout`]).
type DecoderLayout = Vec<(usize, Vec<usize>, DType)>;

/// The decoder for a loaded model, its task and its [`DecoderLayout`].
///
/// Shapes and quantization come from the runtime; each output's `dshape`
/// and box `normalized` flag come from its `edgefirst.json` entry (see
/// [`OutputMetadata`]).
#[allow(clippy::too_many_lines)]
fn build_decoder(
    model: &Model,
    metadata: Option<&dvm_metadata::DvmMetadata>,
    args: &Args,
) -> Result<(Decoder, Task, DecoderLayout)> {
    let task = match metadata.and_then(dvm_metadata::DvmMetadata::task) {
        Some("segment") => Task::Segment,
        _ => Task::Detect,
    };
    let [_, in_h, in_w] = model.input_shape(0);
    #[allow(clippy::cast_precision_loss)]
    let input_dim = in_w.max(in_h) as f32;

    // Normalize output shapes, identify which output is boxes, scores, mask
    // coefficients or protos, and read each one's quantization.
    let n_outputs = model.n_outputs();
    let shapes: Vec<Vec<usize>> = (0..n_outputs)
        .map(|i| normalize_shape(model.output_shape(i)))
        .collect();
    let names = (0..n_outputs)
        .map(|i| model.output_info(i).map(|info| info.layer_name))
        .collect::<std::result::Result<Vec<_>, _>>()?;

    let task = if task == Task::Detect && shapes.iter().any(|s| s.len() == 4) {
        Task::Segment
    } else {
        task
    };
    let layout = output_layout(task, &shapes, &names).map_err(Error::Unsupported)?;

    let mut quants = Vec::with_capacity(n_outputs);
    let mut dtypes = Vec::with_capacity(n_outputs);
    let mut dshapes: Vec<Vec<(DimName, usize)>> = Vec::with_capacity(n_outputs);
    let mut normalized_flags: Vec<Option<bool>> = Vec::with_capacity(n_outputs);

    // Each runtime output's edgefirst.json entry gives its dshape and
    // normalized flag; see `OutputMetadata`.
    let output_metadata = OutputMetadata::new(metadata.iter().flat_map(|m| &m.outputs));

    for (i, shape) in shapes.iter().enumerate() {
        let info = model.output_info(i)?;
        let role = layout.iter().find(|&&(j, _)| j == i).map(|&(_, r)| r);
        let spec = role.and_then(|r| output_metadata.spec(&names[i], shape, r));

        // Some exports name the channel axis of `mask_coefs` `num_features`
        // where the decoder requires `num_protos`.
        let dshape: Vec<(DimName, usize)> = spec
            .map(|s| {
                let mut d = s.dshape_typed();
                d.truncate(shape.len());
                if s.output_type.as_deref() == Some("mask_coefs") {
                    for (name, _) in &mut d {
                        if *name == DimName::NumFeatures {
                            *name = DimName::NumProtos;
                        }
                    }
                }
                d
            })
            .unwrap_or_default();
        let normalized = spec
            .filter(|_| role == Some(OutputRole::Boxes))
            .and_then(|s| s.normalized);

        // Exports that do not declare `normalized` emit boxes in input
        // pixels; dividing the scale by the input size normalizes them.
        let scale = if role == Some(OutputRole::Boxes) && normalized.is_none() && input_dim > 1.0 {
            info.quant.qn / input_dim
        } else {
            info.quant.qn
        };
        let dtype = match (info.bpp, info.quant.is_signed) {
            (1, false) => DType::U8,
            (1, true) => DType::I8,
            (2, false) => DType::U16,
            (2, true) => DType::I16,
            (bpp, signed) => {
                return Err(Error::unsupported(format!(
                    "output {i}: {bpp}-byte {} elements",
                    if signed { "signed" } else { "unsigned" }
                )));
            }
        };
        println!(
            "  Output {i}: {} ({}), {shape:?} {dtype:?} scale {scale} zero point {}",
            role.map_or_else(|| "unused".to_owned(), |r| format!("{r:?}")),
            names[i],
            info.quant.offset
        );
        quants.push(QuantTuple(scale, info.quant.offset));
        dtypes.push(dtype);
        dshapes.push(dshape);
        normalized_flags.push(normalized);
    }
    let normalized_for = |i: usize| Some(normalized_flags[i].unwrap_or(true));
    let boxes = |i: usize| configs::Boxes {
        decoder: DecoderType::Ultralytics,
        quantization: Some(quants[i]),
        shape: shapes[i].clone(),
        dshape: dshape_or_canonical(&dshapes, i, OutputRole::Boxes, &shapes[i]),
        normalized: normalized_for(i),
    };
    let scores = |i: usize| configs::Scores {
        decoder: DecoderType::Ultralytics,
        quantization: Some(quants[i]),
        shape: shapes[i].clone(),
        dshape: dshape_or_canonical(&dshapes, i, OutputRole::Scores, &shapes[i]),
    };

    let builder = match *layout.as_slice() {
        [(bi, _), (si, _)] => {
            DecoderBuilder::new().with_config_yolo_split_det(boxes(bi), scores(si))
        }
        [(bi, _), (si, _), (mi, _), (pi, _)] => DecoderBuilder::new()
            .with_config_yolo_split_segdet(
                boxes(bi),
                scores(si),
                configs::MaskCoefficients {
                    decoder: DecoderType::Ultralytics,
                    quantization: Some(quants[mi]),
                    shape: shapes[mi].clone(),
                    dshape: dshape_or_canonical(
                        &dshapes,
                        mi,
                        OutputRole::MaskCoefficients,
                        &shapes[mi],
                    ),
                },
                configs::Protos {
                    decoder: DecoderType::Ultralytics,
                    quantization: Some(quants[pi]),
                    shape: shapes[pi].clone(),
                    dshape: dshape_or_canonical(&dshapes, pi, OutputRole::Protos, &shapes[pi]),
                },
            ),
        _ => {
            return Err(Error::unsupported(format!(
                "unexpected output layout {layout:?}"
            )));
        }
    };
    // The decoder is built from output configs rather than the schema, so
    // `auto` takes the policy from the metadata here.
    let nms = match args.nms {
        NmsArg::Auto => metadata
            .and_then(|m| m.nms.as_deref())
            .and_then(Nms::from_str_code)
            .unwrap_or(Nms::Auto),
        nms => nms.into(),
    };
    let decoder = builder
        .with_score_threshold(args.threshold)
        .with_iou_threshold(args.iou)
        .with_nms(Some(nms))
        .build()?;
    let layout = layout
        .iter()
        .map(|&(i, _)| (i, shapes[i].clone(), dtypes[i]))
        .collect();
    Ok((decoder, task, layout))
}

/// Whether a model tensor has a file descriptor the HAL can import: a
/// DMA-BUF or shared-memory buffer, not a heap one.
fn has_fd(memory: TensorMemory) -> bool {
    matches!(memory, TensorMemory::DmaBuf | TensorMemory::Shm)
}

/// An input set the ARA-2 reads, and the planar-RGB HAL image the GPU
/// letterboxes into.
///
/// With a DMA-BUF set the image is the set's own buffer. A heap set (a TCP
/// session) cannot be imported, so the image is a separate HAL image that
/// [`Self::stage`] copies into the set.
pub struct ModelInput {
    set: InputSet,
    image: TensorDyn,
    staged: bool,
}

impl ModelInput {
    fn allocate(
        model: &Model,
        processor: &ImageProcessor,
        memory: Option<TensorMemory>,
        (in_w, in_h): (usize, usize),
        dtype: DType,
    ) -> Result<Self> {
        let set = model.allocate_input_set(memory)?;
        let tensor = set.input_tensor(0);
        if has_fd(tensor.memory()) {
            let fd = tensor.clone_fd()?;
            let image = processor.import_image(
                PlaneDescriptor::new(fd.as_fd())?,
                None,
                in_w,
                in_h,
                PixelFormat::PlanarRgb,
                dtype,
                None,
            )?;
            return Ok(Self {
                set,
                image,
                staged: false,
            });
        }
        let image = processor.create_image(
            in_w,
            in_h,
            PixelFormat::PlanarRgb,
            dtype,
            None,
            CpuAccess::Read,
        )?;
        Ok(Self {
            set,
            image,
            staged: true,
        })
    }

    /// The image `convert` renders into.
    fn image(&mut self) -> &mut TensorDyn {
        &mut self.image
    }

    /// Make the rendered frame visible to the model.
    fn stage(&self) -> Result<()> {
        if self.staged {
            let src = self.image.map_bytes(CpuAccess::Read)?;
            let mut map = self.set.input_tensor(0).map()?;
            let dst = map.as_mut_slice();
            let n = dst.len().min(src.len());
            dst[..n].copy_from_slice(&src[..n]);
        }
        Ok(())
    }

    fn set(&self) -> &InputSet {
        &self.set
    }
}

/// An output set the ARA-2 writes into, and the HAL tensors the decoder
/// reads, in [`DecoderLayout`] order.
///
/// With a DMA-BUF set the tensors view the set's own buffers. A heap set
/// cannot be viewed, so the tensors are separate buffers that
/// [`Self::unstage`] copies the set into.
pub struct OutputBuffers {
    set: OutputSet,
    tensors: Vec<TensorDyn>,
    /// The runtime output index of each tensor, when it is a copy.
    staged: Option<Vec<usize>>,
}

impl OutputBuffers {
    fn allocate(
        model: &Model,
        memory: Option<TensorMemory>,
        layout: &DecoderLayout,
    ) -> Result<Self> {
        let set = model.allocate_output_set(memory)?;
        let viewed = layout
            .iter()
            .all(|(i, _, _)| has_fd(set.output_tensor(*i).memory()));
        let tensors = layout
            .iter()
            .map(|(i, shape, dtype)| {
                if viewed {
                    let fd = set.output_tensor(*i).clone_fd()?;
                    Ok(TensorDyn::from_fd(fd, shape, *dtype, None)?)
                } else {
                    Ok(TensorDyn::new(
                        shape,
                        *dtype,
                        Some(TensorMemory::Mem),
                        None,
                    )?)
                }
            })
            .collect::<Result<Vec<_>>>()?;
        let staged = (!viewed).then(|| layout.iter().map(|(i, _, _)| *i).collect());
        Ok(Self {
            set,
            tensors,
            staged,
        })
    }

    fn set(&self) -> &OutputSet {
        &self.set
    }

    /// Make the model's outputs visible to the decoder.
    fn unstage(&self) -> Result<()> {
        if let Some(indices) = &self.staged {
            for (&i, tensor) in indices.iter().zip(&self.tensors) {
                let src = self.set.output_tensor(i).map()?;
                let src = src.as_slice();
                let mut dst = tensor.map_bytes(CpuAccess::Write)?;
                let n = dst.len().min(src.len());
                dst[..n].copy_from_slice(&src[..n]);
            }
        }
        Ok(())
    }

    fn refs(&self) -> Vec<&TensorDyn> {
        self.tensors.iter().collect()
    }
}

/// An RGBA DMA-BUF of `width` x `height` for the compositor, with its fd
/// and row stride in bytes.
///
/// With GL only the GPU and the compositor touch it, so it is declared
/// without CPU access, which the HAL serves from uncached memory where the
/// system has it; the CPU renderer used without GL reads and writes it.
fn display_buffer(
    processor: &ImageProcessor,
    width: usize,
    height: usize,
) -> Result<(TensorDyn, OwnedFd, u32)> {
    let access = if processor.opengl.is_some() {
        CpuAccess::None
    } else {
        CpuAccess::ReadWrite
    };
    let image = processor
        .create_image(
            width,
            height,
            PixelFormat::Rgba,
            DType::U8,
            Some(TensorMemory::DmaBuf),
            access,
        )
        .map_err(|e| Error::display(format!("cannot allocate a DMA-BUF canvas: {e}")))?;
    let stride = image.effective_row_stride().unwrap_or(width * 4);
    let stride = u32::try_from(stride).map_err(|_| Error::display("canvas stride out of range"))?;
    let fd = image.clone_fd()?;
    Ok((image, fd, stride))
}

/// The overlay background for a camera frame. GL composites the frame's
/// native NV12 or YUYV layout directly; G2D and the CPU copy the background
/// byte-for-byte, so without GL the frame is converted to the canvas's RGBA
/// format first.
fn overlay_background<'a>(
    processor: &mut ImageProcessor,
    frame: &'a TensorDyn,
    rgba: &'a mut Option<TensorDyn>,
) -> Result<&'a TensorDyn> {
    match rgba {
        Some(background) => {
            processor.convert(frame, background, None)?;
            Ok(background)
        }
        None => Ok(frame),
    }
}

// ── Main ────────────────────────────────────────────────────────────────────

/// Frames per timing report.
const REPORT_EVERY: u32 = 30;

/// Display buffers drawn into in turn.
const CANVASES: usize = 4;

#[allow(clippy::too_many_lines, clippy::cast_precision_loss)]
fn main() -> Result<()> {
    let args = Args::parse();
    let (cam_w, cam_h) = (args.width, args.height);
    let format = PixelFormat::from(args.format);
    let color_mode = ColorMode::from(args.color_mode);
    let (exposure, gain) = if args.auto_exposure {
        (None, None)
    } else {
        (args.exposure, args.gain)
    };

    // ── 1. Model metadata ───────────────────────────────────────────────
    // The DVM's embedded metadata (task type, compilation target, PPA stats)
    // and class labels. Falls back to COCO-80 labels if none are embedded.
    let dvm = std::fs::read(&args.model)?;
    let metadata = dvm_metadata::read_metadata(&dvm)?;
    let dvm_labels = dvm_metadata::read_labels(&dvm)?;
    drop(dvm);
    let n_labels = if dvm_labels.is_empty() {
        COCO.len()
    } else {
        dvm_labels.len()
    };
    println!("Model: {}", args.model.display());
    if let Some(ref m) = metadata
        && let Some(ref comp) = m.compilation
        && let Some(ref ppa) = comp.ppa
    {
        println!(
            "  Target: {:?}, IPS: {:.0}, Power: {:.0} mW",
            comp.target,
            ppa.ips.unwrap_or(0.0),
            ppa.power_mw.unwrap_or(0.0)
        );
    }

    // ── 2. ARA-2 session and model ──────────────────────────────────────
    let session = match &args.socket {
        Some(path) => Session::create_via_unix_socket(path)?,
        None => Session::connect()?,
    };
    let endpoint = session
        .list_endpoints()?
        .into_iter()
        .next()
        .ok_or_else(|| Error::unsupported("no ARA-2 endpoint; is rt-sdk-ara2.service running?"))?;
    let stats = endpoint.dram_statistics()?;
    println!(
        "Endpoint: {:?}, DRAM: {:.0} / {:.0} MB free",
        endpoint.check_status()?,
        stats.free_size as f64 / 1_048_576.0,
        stats.dram_size as f64 / 1_048_576.0,
    );
    let model = endpoint.load_model_from_file(&args.model)?;
    // DMA-BUF buffers need a session that can pass file descriptors (UNIX);
    // over TCP they fall back to heap buffers.
    let memory = if session.supports_fd_passing() {
        Some(TensorMemory::DmaBuf)
    } else {
        println!("  Proxy over TCP: copying the model's input and outputs");
        None
    };

    let [in_c, in_h, in_w] = model.input_shape(0);
    let input_dtype = if model.input_quants(0).is_signed {
        DType::I8
    } else {
        DType::U8
    };
    println!("  Input: {in_c}x{in_h}x{in_w} (CHW) {input_dtype:?}");

    // ── 3. Decoder ──────────────────────────────────────────────────────
    let (decoder, task, decoder_layout) = build_decoder(&model, metadata.as_ref(), &args)?;
    let is_segmentation = task == Task::Segment;
    println!("  Task: {task:?}, {n_labels} classes");

    // ── 4. HAL processors, model I/O and display canvas ─────────────────
    // Preprocessing and overlay drawing use separate processors. Sharing one
    // corrupts the next frame's model input on i.MX95 (Mali): state left by
    // drawing garbles the following convert into the model's input buffer,
    // letterbox padding included, and detection quietly degrades.
    let processor = ImageProcessor::new()?;
    let mut overlay_processor = ImageProcessor::new()?;
    if let Some(ClassColors(ref colors)) = args.class_colors {
        overlay_processor.set_class_colors(colors)?;
    }
    let slots = (0..args.slots.get())
        .map(|_| {
            ModelInput::allocate(&model, &processor, memory, (in_w, in_h), input_dtype)
                .map(pipeline::Slot::new)
        })
        .collect::<Result<Vec<_>>>()?;
    // One output set each for the npu thread, the hand-off to decode and
    // the decode thread, so neither waits on the other for a buffer.
    let output_pool = (0..3)
        .map(|_| OutputBuffers::allocate(&model, memory, &decoder_layout))
        .collect::<Result<Vec<_>>>()?;
    let letterbox = ConvertOptions::new().letterbox([114, 114, 114, 255]);

    // The window, and so the canvas, is the capture size unless the
    // compositor sized it for fullscreen.
    let mut display = WaylandDisplay::new(cam_w, cam_h, "ARA-2 YOLOv8 Live", args.fullscreen)?;
    let (disp_w, disp_h) = display.size();
    println!("Display: {disp_w}x{disp_h}");
    if (disp_w * cam_h).abs_diff(disp_h * cam_w) * 100 > disp_w * cam_h {
        eprintln!(
            "WARNING: capture {cam_w}x{cam_h} and display {disp_w}x{disp_h} differ in \
             aspect ratio; the picture is stretched to fill the screen"
        );
    }
    // With GL, a canvas the size of the camera frame lets the HAL draw over
    // the frame itself, and the compositor scales the canvas to the window as
    // it composites; otherwise each frame is first converted to the window's
    // size.
    let (canvas_w, canvas_h) = if (disp_w, disp_h) != (cam_w, cam_h)
        && overlay_processor.opengl.is_some()
        && display.scale_buffers(cam_w, cam_h)?
    {
        (cam_w, cam_h)
    } else {
        (disp_w, disp_h)
    };
    if (canvas_w, canvas_h) != (disp_w, disp_h) {
        println!("Canvas:  {canvas_w}x{canvas_h}, scaled by the compositor");
    }
    // The outline is drawn in canvas pixels; keep its width on screen.
    if let Some(width) = args.line_width {
        let width = (width.get() as usize * canvas_w).div_ceil(disp_w);
        overlay_processor.set_box_line_width(
            u32::try_from(width).map_err(|_| Error::unsupported("--line-width out of range"))?,
        )?;
    }

    // Each frame is drawn into a canvas the compositor has released, so it
    // never displays a frame mid-draw. It can hold three: the one on screen,
    // one waiting for the next refresh and the newest commit.
    let mut canvases = Vec::with_capacity(CANVASES);
    let mut canvas_fds = Vec::with_capacity(CANVASES);
    let mut canvas_stride = 0;
    for _ in 0..CANVASES {
        let (canvas, fd, stride) = display_buffer(&overlay_processor, canvas_w, canvas_h)?;
        canvases.push(canvas);
        canvas_fds.push(fd);
        canvas_stride = stride;
    }
    // Drawing composites onto a background of the canvas's size and, without
    // GL, of its RGBA format, so either difference needs a converted copy of
    // each frame.
    let mut rgba_background =
        if overlay_processor.opengl.is_none() || (canvas_w, canvas_h) != (cam_w, cam_h) {
            Some(overlay_processor.create_image(
                canvas_w,
                canvas_h,
                PixelFormat::Rgba,
                DType::U8,
                None,
                CpuAccess::ReadWrite,
            )?)
        } else {
            None
        };

    // ── 5. Camera ───────────────────────────────────────────────────────
    let manager = CameraManager::new()?;
    let cameras = manager.cameras();
    let camera = match args.camera_name {
        Some(ref name) => cameras.iter().find(|c| c.id() == name.as_str()),
        None => cameras.get(0),
    };
    let Some(camera) = camera else {
        let available: Vec<String> = cameras.iter().map(|c| c.id().to_string()).collect();
        return Err(Error::camera(format!(
            "camera not found; available: [{}]",
            available.join(", ")
        )));
    };
    println!("Camera: {}", camera.id());
    let mut camera = camera.acquire()?;

    let mut config = camera
        .generate_configuration(&[StreamRole::VideoRecording])
        .ok_or_else(|| Error::camera("cannot generate a configuration"))?;
    {
        let mut stream_cfg = config.get_mut(0).expect("one stream requested");
        stream_cfg.set_pixel_format(libcamera_format(format));
        stream_cfg.set_size(libcamera::geometry::Size {
            width: u32::try_from(cam_w).map_err(|_| Error::camera("width out of range"))?,
            height: u32::try_from(cam_h).map_err(|_| Error::camera("height out of range"))?,
        });
    }
    match config.validate() {
        CameraConfigurationStatus::Valid => {}
        CameraConfigurationStatus::Adjusted => {
            // libcamera may adjust the buffer count, stride or color space,
            // which the import follows. The canvas, window and letterbox are
            // all sized from the request, so a different size or format would
            // be drawn misregistered.
            let cfg = config.get(0).expect("one stream requested");
            let size = cfg.get_size();
            if (size.width as usize, size.height as usize) != (cam_w, cam_h)
                || cfg.get_pixel_format() != libcamera_format(format)
            {
                return Err(Error::camera(format!(
                    "camera cannot capture {cam_w}x{cam_h} {format:?}; it offered {}x{} {:?}",
                    size.width,
                    size.height,
                    cfg.get_pixel_format()
                )));
            }
        }
        CameraConfigurationStatus::Invalid => {
            return Err(Error::camera(format!(
                "camera cannot produce {format:?}; on i.MX95 set \
                 LIBCAMERA_PIPELINES_MATCH_LIST=nxp/neo to capture through the ISP"
            )));
        }
    }
    camera.configure(&mut config)?;
    let (stream, stride, color_space) = {
        let cfg = config.get(0).expect("one stream requested");
        let stream = cfg
            .stream()
            .ok_or_else(|| Error::camera("configured stream missing"))?;
        (stream, cfg.get_stride() as usize, cfg.get_color_space())
    };

    let mut allocator = FrameBufferAllocator::new(&camera);
    let buffers = allocator.alloc(&stream)?;
    let n_buffers = buffers.len();
    println!(
        "  Capture: {cam_w}x{cam_h} {format:?}, stride {stride}, {n_buffers} buffers, {color_space:?}"
    );
    let mut requests = Vec::with_capacity(n_buffers);
    for (i, buffer) in buffers.into_iter().enumerate() {
        let mut request = camera
            .create_request(Some(i as u64))
            .ok_or_else(|| Error::camera("cannot create a request"))?;
        request.add_buffer(&stream, buffer)?;
        requests.push(request);
    }
    let mut frames = FrameCache {
        entries: (0..n_buffers).map(|_| None).collect(),
        width: cam_w,
        height: cam_h,
        stride,
        format,
        colorimetry: color_space.map(colorimetry),
    };

    let (events_tx, events) = mpsc::channel();
    let camera_events = events_tx.clone();
    camera.on_request_completed(move |request| {
        let _ = camera_events.send(pipeline::Event::Frame(request));
    });

    // ── 6. Live loop ────────────────────────────────────────────────────
    // Applied at start and on the first round of requests; the pipeline
    // keeps manual exposure and gain until a request changes them.
    let manual = manual_exposure(&camera, exposure, gain)?;
    camera.start(manual.as_deref()).map_err(|e| {
        if manual.is_some() {
            Error::camera(format!("camera rejected --exposure/--gain controls: {e}"))
        } else {
            e.into()
        }
    })?;
    for mut request in requests {
        if let Some(manual) = manual.as_deref() {
            request
                .controls_mut()
                .merge(manual, MergePolicy::OverwriteExisting);
        }
        camera.queue_request(request).map_err(|(_, e)| e)?;
    }
    println!("Running -- close the window or press Ctrl+C to stop\n");

    // Pipeline channels. Each is bounded by what it holds: one frame
    // waiting to be letterboxed, the slots, one frame between npu and
    // decode, and the output-buffer pool.
    let (frame_tx, frame_rx) = mpsc::sync_channel::<pipeline::Frame>(1);
    let (free_tx, free_rx) = mpsc::channel();
    for slot in slots {
        free_tx.send(slot).expect("receiver is alive");
    }
    let (prepared_tx, prepared_rx) = mpsc::sync_channel(1);
    let (pool_tx, pool_rx) = mpsc::channel();
    for buffers in output_pool {
        pool_tx.send(buffers).expect("receiver is alive");
    }
    let (inferred_tx, inferred_rx) = mpsc::sync_channel(1);

    let t_start = Instant::now();
    let mut window_start = t_start;
    let mut frame_count: u64 = 0;
    // pre, infer, npu, decode, background, draw, present, latency
    let mut window = [Duration::ZERO; 8];
    let mut dropped: u64 = 0;
    let mut skipped: u64 = 0;
    let mut exposure_range = ExposureRange::default();
    let mut status_lines: u32 = 0;
    let stderr_is_terminal = std::io::stderr().is_terminal();
    let mut last_detections = 0;
    // Requests whose frames are in the pipeline, by buffer index.
    let mut in_flight: HashMap<usize, libcamera::request::Request> = HashMap::new();

    std::thread::scope(|scope| -> Result<()> {
        let decoder = &decoder;
        let stages = [
            scope.spawn(move || {
                pipeline::preprocess(processor, letterbox, &frame_rx, &free_rx, &prepared_tx)
            }),
            scope.spawn(move || {
                pipeline::infer(model, &prepared_rx, &free_tx, &pool_rx, &inferred_tx)
            }),
            scope.spawn(move || {
                pipeline::decode(decoder, is_segmentation, &inferred_rx, &pool_tx, &events_tx)
            }),
        ];

        let looped = (|| -> Result<()> {
            while display.is_open()? {
                // Everything that arrived while the last frame was drawn:
                // decoded frames are drawn in order, and of the camera
                // frames only the newest enters the pipeline.
                let first = events
                    .recv_timeout(Duration::from_secs(5))
                    .map_err(|_| Error::camera("no frame within 5 s"))?;
                let mut newest = None;
                for event in std::iter::once(first).chain(events.try_iter()) {
                    match event {
                        pipeline::Event::Frame(request) => {
                            exposure_range.add(request.metadata());
                            if let Some(older) = newest.replace(request) {
                                requeue(&camera, older)?;
                                dropped += 1;
                            }
                        }
                        pipeline::Event::Decoded(result) => {
                            let pipeline::Decoded {
                                frame,
                                detections,
                                masks,
                                protos,
                                times,
                            } = *result;
                            let t0 = Instant::now();
                            let (mut t1, mut t2) = (t0, t0);
                            if let Some(back) = display.free_buffer(&canvas_fds)? {
                                let background = overlay_background(
                                    &mut overlay_processor,
                                    &frame.image,
                                    &mut rgba_background,
                                )?;
                                t1 = Instant::now();
                                let overlay = MaskOverlay::default()
                                    .with_background(background)
                                    .with_convert_options(&letterbox, cam_w, cam_h, in_w, in_h)
                                    .with_color_mode(color_mode);
                                if let Some(ref protos) = protos {
                                    overlay_processor.draw_proto_masks(
                                        &mut canvases[back],
                                        &detections,
                                        protos,
                                        overlay,
                                    )?;
                                } else {
                                    overlay_processor.draw_decoded_masks(
                                        &mut canvases[back],
                                        &detections,
                                        &masks,
                                        overlay,
                                    )?;
                                }
                                t2 = Instant::now();
                                display.present(canvas_fds[back].as_fd(), canvas_stride)?;
                            } else {
                                skipped += 1;
                            }
                            let t3 = Instant::now();

                            // The frame has been drawn or skipped, so its buffer can be
                            // captured into again.
                            let latency = frame.entered.elapsed();
                            frames.put(frame.index, frame.image);
                            if let Some(request) = in_flight.remove(&frame.index) {
                                requeue(&camera, request)?;
                            }

                            for (acc, d) in window.iter_mut().zip([
                                times.preprocess,
                                times.infer,
                                times.npu,
                                times.decode,
                                t1 - t0,
                                t2 - t1,
                                t3 - t2,
                                latency,
                            ]) {
                                *acc += d;
                            }
                            last_detections = detections.len();
                            frame_count += 1;
                            if frame_count.is_multiple_of(u64::from(REPORT_EVERY)) {
                                let fps =
                                    f64::from(REPORT_EVERY) / window_start.elapsed().as_secs_f64();
                                window_start = Instant::now();
                                let [pre, infer, npu, decode, bg, draw, present, latency] =
                                    window.map(|d| (d / REPORT_EVERY).as_secs_f64() * 1000.0);
                                let status = format!(
                                    "  FPS: {fps:5.1}  pre:{pre:4.1} inf:{infer:5.1} \
                                     npu:{npu:4.1} dec:{decode:5.1} bg:{bg:4.1} draw:{draw:5.1} \
                                     disp:{present:4.1} lat:{latency:5.1} ms  \
                                     drop:{dropped} skip:{skipped} det:{last_detections:<3} {exposure_range}"
                                );
                                // The first window includes frames captured before the
                                // controls took effect.
                                status_lines += 1;
                                if status_lines == 2 {
                                    if stderr_is_terminal {
                                        eprintln!();
                                    }
                                    check_exposure((exposure, gain), &exposure_range);
                                }
                                // A terminal redraws one line in place; a log, such as
                                // the journal, only records complete lines.
                                if stderr_is_terminal {
                                    eprint!("\r{status}  ");
                                } else {
                                    eprintln!("{status}");
                                }
                                exposure_range = ExposureRange::default();
                                window = [Duration::ZERO; 8];
                            }
                        }
                    }
                }

                // Feed the newest frame to the pipeline, or give it back to
                // the camera when the pipeline is still busy.
                if let Some(request) = newest {
                    let index = usize::try_from(request.cookie())
                        .map_err(|_| Error::camera("request cookie out of range"))?;
                    let buffer: &FrameBuffer = request
                        .buffer(&stream)
                        .ok_or_else(|| Error::camera("completed request has no buffer"))?;
                    let image = frames.take(index, &overlay_processor, buffer)?;
                    let frame = pipeline::Frame {
                        index,
                        image,
                        entered: Instant::now(),
                    };
                    match frame_tx.try_send(frame) {
                        Ok(()) => {
                            in_flight.insert(index, request);
                        }
                        Err(mpsc::TrySendError::Full(frame)) => {
                            frames.put(frame.index, frame.image);
                            requeue(&camera, request)?;
                            dropped += 1;
                        }
                        // A stage has stopped; its error is collected below.
                        Err(mpsc::TrySendError::Disconnected(_)) => break,
                    }
                }
            }
            Ok(())
        })();

        // Closing the first channel winds the stages down in order.
        drop(frame_tx);
        for stage in stages {
            stage
                .join()
                .map_err(|_| Error::unsupported("a pipeline thread panicked"))??;
        }
        looped
    })?;

    eprintln!();
    camera.stop()?;
    if frame_count > 0 {
        let elapsed = t_start.elapsed().as_secs_f64();
        println!(
            "Processed {frame_count} frames in {elapsed:.1}s ({:.1} FPS average)",
            frame_count as f64 / elapsed
        );
    }
    Ok(())
}

#[cfg(test)]
mod offline_tests {
    use super::*;

    fn exposure(args: &[&str]) -> (Option<i32>, Option<f32>) {
        let args = Args::try_parse_from(["yolov8_live", "model.dvm"].iter().chain(args))
            .expect("arguments parse");
        if args.auto_exposure {
            (None, None)
        } else {
            (args.exposure, args.gain)
        }
    }

    #[test]
    fn auto_exposure_cancels_earlier_values() {
        let fixed = (Some(10000), Some(2.0));
        assert_eq!(exposure(&["--exposure", "10000", "--gain", "2"]), fixed);
        assert_eq!(
            exposure(&["--exposure", "10000", "--gain", "2", "--auto-exposure"]),
            (None, None)
        );
        assert_eq!(
            exposure(&["--auto-exposure", "--exposure", "10000", "--gain", "2"]),
            fixed
        );
    }

    #[test]
    fn exposure_and_gain_go_together() {
        assert!(Args::try_parse_from(["yolov8_live", "m.dvm", "--exposure", "10000"]).is_err());
        assert!(Args::try_parse_from(["yolov8_live", "m.dvm", "--gain", "2"]).is_err());
    }

    #[test]
    fn class_colors_parse() {
        let ClassColors(colors) = parse_class_colors("FF0000,#00ff80").expect("valid colours");
        assert_eq!(colors, [[255, 0, 0, 255], [0, 255, 128, 255]]);
        assert!(parse_class_colors("FF00").is_err());
        assert!(parse_class_colors(&["000000"; 21].join(",")).is_err());
    }
}
