//! # YOLOv8 Live Camera Inference on ARA-2 NPU
//!
//! Captures NV12 or YUYV frames from a camera via libcamera, runs YOLOv8
//! detection or instance segmentation on the ARA-2 NPU, and displays the
//! results in a native Wayland window. Overlays are composited onto the
//! camera frame by the EdgeFirst HAL (`edgefirst-image`).
//!
//! Display uses the `zwp_linux_dmabuf_v1` Wayland protocol to submit the
//! RGBA canvas DMA-BUF directly to the compositor — no EGL or OpenGL on the
//! client side.
//!
//! ## Pipeline
//!
//! ```text
//! libcamera (NV12 | YUYV DMA-BUF)
//!   -> HAL import            (cached per camera buffer)
//!   -> HAL convert           (letterbox into a planar-RGB input DMA-BUF)
//!   -> ARA-2 inference       (outputs into a pooled DMA-BUF set)
//!   -> HAL decode            (in place on the output DMA-BUFs)
//!   -> HAL draw              (composite onto an RGBA DMA-BUF canvas)
//!   -> Wayland               (canvas DMA-BUF -> wl_buffer -> compositor)
//! ```
//!
//! The stages run on separate threads so consecutive frames overlap (see
//! [`pipeline`]). `--slots` sets the number of input buffers the letterbox
//! and inference stages alternate between (default 2; 1 runs them back to
//! back).
//!
//! Every hop is a DMA-BUF hand-off when the ARA-2 proxy is on a UNIX socket.
//! Over TCP the proxy cannot receive file descriptors, so the model's input
//! and outputs are heap buffers, copied to and from the HAL images around
//! each inference.
//!
//! ## Models
//!
//! Official pre-trained models are published in the EdgeFirst model zoo on
//! Hugging Face:
//!
//! - Detection: <https://huggingface.co/EdgeFirst/yolov8-det>
//! - Segmentation: <https://huggingface.co/EdgeFirst/yolov8-seg>
//!
//! Each repository ships one directory per target; the ARA-2 builds are the
//! int16 `.dvm` exports under `ara240/`, in `n`/`s`/`m` sizes.
//!
//! ```sh
//! curl -LO https://huggingface.co/EdgeFirst/yolov8-det/resolve/main/ara240/yolov8n-det-int16.dvm
//! curl -LO https://huggingface.co/EdgeFirst/yolov8-seg/resolve/main/ara240/yolov8n-seg-int16.dvm
//! ```
//!
//! Every export embeds an `edgefirst.json` schema and the class `labels.txt`
//! in a ZIP trailer appended to the `.dvm`. That schema is where the
//! per-output `normalized` flag and named `dshape` come from — the NPU
//! runtime reports neither, and a model emitting pixel-space boxes is
//! misread without them. An export with no trailer still runs, falling back
//! to the built-in COCO labels and a canonical Ultralytics axis naming.
//!
//! This example pins `DecoderVersion::Yolov8`, so it decodes the
//! `yolov8-det` and `yolov8-seg` repositories.
//!
//! ## Usage
//!
//! See `yolov8_live --help` for the full flag reference (generated by clap).
//!
//! `--nms auto` follows the policy in the model's `edgefirst.json`; `agnostic`
//! also suppresses overlapping boxes of different classes, which removes the
//! double-labelled objects a model unsure between two classes produces.
//!
//! `--fullscreen` asks the compositor for a fullscreen window and renders at
//! the output's resolution; the camera frame is scaled to fill it, so capture
//! at the display's aspect ratio to keep the picture undistorted.
//!
//! `--class-colors` sets the box colour of each class, in label order, as hex
//! `RRGGBB` values, and `--line-width` the box outline width in display
//! pixels.
//!
//! `--exposure` (microseconds) and `--gain` (analogue gain), given together,
//! turn the camera's automatic exposure off and hold the sensor at fixed
//! values, which stops the frame-to-frame brightness changes the AGC makes.
//! Mains lighting flickers at twice the mains frequency, so an exposure of
//! whole flicker periods (8333 or 16666 µs for 60 Hz, 10000 µs for 50 Hz)
//! collects the same light in every frame. `--auto-exposure` cancels both
//! when it follows them on the command line. A warning names any control
//! the camera lacks, and the second status line's frames are checked against
//! the requested values. Each status line reports the range of exposure and
//! gain the sensor used since the previous one.
//!
//! Some sensors also run an automatic exposure of their own, beneath
//! libcamera, which libcamera leaves on. The Phytec AR0234 does: it fights
//! `--exposure` and `--gain`, so the picture flickers while the frames still
//! report steady values. Turn it off before starting the example:
//!
//! ```sh
//! v4l2-ctl -d /dev/cam-csi1-port0 -c auto_exposure=1,autogain_analogue=0
//! ```
//!
//! On i.MX 95 the `imx8-isi` pipeline handler claims the ISI before the
//! `NeoISP` handler does, and offers only raw Bayer that the HAL cannot
//! convert. Unless the image's `/etc/libcamera` configuration already
//! prefers it, set `LIBCAMERA_PIPELINES_MATCH_LIST=nxp/neo` so the sensor is
//! captured through the ISP, which produces NV12 and YUYV.
//!
//! ## Requirements
//!
//! - libcamera (camera capture)
//! - ARA-2 proxy service running
//! - Wayland compositor (Weston) with `zwp_linux_dmabuf_v1` support

